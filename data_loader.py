_PRICE_GROUPS = {}  # {filename: {ticker: Series}} ë¯¸ë¦¬ ë¶„í•´?•´?„œ ????¥

def _load_price_parquet(filename):
    """parquet ?ŒŒ?¼ ë¡œë“œ (?•œ ë²ˆë§Œ + ì¢…ëª©ë³? ?‚¬? „ ë¶„í•´)"""
    path = os.path.join(CACHE_DIR, filename)
    if not os.path.exists(path):
        return None
    if path in _PRICE_DF_CACHE:
        return _PRICE_DF_CACHE[path]

    df = pd.read_parquet(path)
    # ticker ì»¬ëŸ¼?„ 6?ë¦? ë¬¸ì?—´ë¡? ? •ê·œí™” (?˜¼?•© ????… ë°©ì??)
    df['ticker'] = df['ticker'].astype(str).str.lstrip('A').str.zfill(6)
    df['date'] = pd.to_datetime(df['date'])

    # ì¢…ëª©ë³„ë¡œ ë¯¸ë¦¬ ë¶„í•´?•´?„œ ????¥ (ì¡°íšŒ ?‹œ? ?— ?¸?±?‹± ë¶ˆí•„?š”)
    print(f'  [data] {filename} ì¢…ëª©ë³? ë¶„í•´ ì¤?...')
    groups = {}
    for ticker, grp in df.groupby('ticker'):
        s = grp.set_index('date')['value'].sort_index()
        # ì¤‘ë³µ ?‚ ì§? ? œê±? (ë§ˆì??ë§? ê°? ?œ ì§?)
        s = s[~s.index.duplicated(keep='last')]
        groups[ticker] = s
    _PRICE_GROUPS[path] = groups
    _PRICE_DF_CACHE[path] = df  # ?˜¸?™˜?„±?„ ?œ„?•´ ?œ ì§?
    print(f'  [data] {filename} OK {len(groups)} ì¢…ëª© ?¸?±?‹± ?™„ë£?')
