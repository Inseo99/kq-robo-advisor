def classify_regime(macro):
    """매크�? ?��?��?���? ?��?�� �?�? 분류"""
    try:
        gdp = macro.get('gdp')
        rate = macro.get('rate')

        # 최근 GDP ?��?���?
        gdp_col = [c for c in gdp.columns if '?��?���?' in c][0]
        gdp_recent = gdp[gdp_col].dropna().iloc[-4:].mean() * 100  # 최근 1?�� ?���?
        # 최근 ?��?���? ?��?��?��?�� (�?�?10?�� - �?�?1?��)
        long_col  = [c for c in rate.columns if '�?�?10?��' in c][0]
        short_col = [c for c in rate.columns if '�?�?1?��' in c][0]
        spread = (rate[long_col] - rate[short_col]).dropna().iloc[-30:].mean()

        # ?��?�� 4분면 분류
        growth_up = gdp_recent > 0.5      # 분기 0.5% ?��?��
        inflation_up = spread < 0.5         # ?��?���? ?—�?�� = ?��?��?��/긴축

        if growth_up and not inflation_up:   regime = '골디?��?��'
        elif growth_up and inflation_up:     regime = '리플?��?��?��'
        elif not growth_up and inflation_up: regime = '?��?��그플?��?��?��'
        else:                                regime = '?��?��?��?��?��'

        return dict(regime=regime, gdp=round(gdp_recent,2),
                    spread=round(spread,2), growth_up=growth_up, inflation_up=inflation_up)
    except Exception as e:
        return dict(regime='리플?��?��?��', gdp=0, spread=0)

