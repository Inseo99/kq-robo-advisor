def load_stocks(markets=('KOSPI','KOSDAQ')):
    """
    ë°˜í™˜: {ticker(6?ë¦?): {'name','market','sector','industry','first_year'}}
    ê°??¥ ìµœê·¼ ?‹œ?Š¸(26) ê¸°ì???œ¼ë¡? ? •ë³? ?ˆ˜ì§? + 2014~2026 ? „ì²? ì¢…ëª© ?¬?•¨
    """
    pq = os.path.join(CACHE_DIR, 'stocks.parquet')
    src = _find(_PATTERNS['stocks'])

    if _needs_rebuild(pq, src):
        if src is None:
            return {}
        print('  [data] ì¢…ëª© ? •ë³? ?ŒŒ?‹± ì¤?...')
        xl = pd.ExcelFile(src)
        all_rows = []
        for sheet in xl.sheet_names:
            year = 2000 + int(sheet)
            df = pd.read_excel(src, sheet_name=sheet, dtype={'ì½”ë“œ':str})
            df['year'] = year
            all_rows.append(df)
        full = pd.concat(all_rows, ignore_index=True)
        full['ticker'] = full['ì½”ë“œ'].str.lstrip('A').str.zfill(6)
        # ê°??¥ ìµœê·¼ ? •ë³´ë?? ?š°?„  + first_year ë³´ì¡´
        full = full.sort_values('year')
        first_year = full.groupby('ticker')['year'].min()
        latest     = full.groupby('ticker').last()
        latest['first_year'] = first_year
        latest.to_parquet(pq)
    df = pd.read_parquet(pq)

    df = df[df['?ƒ?¥?œ ?‹œ?¥'].isin(markets)]
    out = {}
    for ticker, row in df.iterrows():
        out[ticker] = dict(
            name      = str(row.get('ì½”ë“œëª?','')),
            market    = str(row.get('?ƒ?¥?œ ?‹œ?¥','')),
            sector    = str(row.get('FnGuide Sector','')),
            industry  = str(row.get('FnGuide Industry','')),
            first_year= int(row.get('first_year', 2014)),
        )
    return out

