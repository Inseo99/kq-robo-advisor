def classify_regime(macro):
    """ë§¤í¬ë¡? ?°?´?„°ë¡? ?˜„?¬ êµ?ë©? ë¶„ë¥˜"""
    try:
        gdp = macro.get('gdp')
        rate = macro.get('rate')

        # ìµœê·¼ GDP ?„±?¥ë¥?
        gdp_col = [c for c in gdp.columns if '?„±?¥ë¥?' in c][0]
        gdp_recent = gdp[gdp_col].dropna().iloc[-4:].mean() * 100  # ìµœê·¼ 1?…„ ?‰ê·?
        # ìµœê·¼ ?¥?‹¨ê¸? ?Š¤?”„? ˆ?“œ (êµ?ê³?10?…„ - êµ?ê³?1?…„)
        long_col  = [c for c in rate.columns if 'êµ?ê³?10?…„' in c][0]
        short_col = [c for c in rate.columns if 'êµ?ê³?1?…„' in c][0]
        spread = (rate[long_col] - rate[short_col]).dropna().iloc[-30:].mean()

        # ?‹¨?ˆœ 4ë¶„ë©´ ë¶„ë¥˜
        growth_up = gdp_recent > 0.5      # ë¶„ê¸° 0.5% ?´?ƒ
        inflation_up = spread < 0.5         # ?¥?‹¨ê¸? ?—­? „ = ?¸?”Œ? ˆ/ê¸´ì¶•

        if growth_up and not inflation_up:   regime = 'ê³¨ë””?½?Š¤'
        elif growth_up and inflation_up:     regime = 'ë¦¬í”Œ? ˆ?´?…˜'
        elif not growth_up and inflation_up: regime = '?Š¤?ƒœê·¸í”Œ? ˆ?´?…˜'
        else:                                regime = '?””?”Œ? ˆ?´?…˜'

        return dict(regime=regime, gdp=round(gdp_recent,2),
                    spread=round(spread,2), growth_up=growth_up, inflation_up=inflation_up)
    except Exception as e:
        return dict(regime='ë¦¬í”Œ? ˆ?´?…˜', gdp=0, spread=0)

